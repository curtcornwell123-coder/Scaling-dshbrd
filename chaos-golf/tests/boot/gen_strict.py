"""Generate strict.luau from Roblox's Full-API-Dump.json: which properties a game script may not
read or write (ReadOnly / NotScriptable tags, or Read/Write security above "None"), plus the real
class hierarchy. The mock enforces it so boot tests fail the way real Roblox would.

Usage: python3 gen_strict.py Full-API-Dump.json   (writes strict.luau next to this file)
Dump: https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/Full-API-Dump.json
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(path):
    dump = json.load(open(path))
    supers, reads, writes, creatable = {}, {}, {}, {}
    for c in dump["Classes"]:
        name = c["Name"]
        supers[name] = c.get("Superclass") or ""
        tags = [t for t in (c.get("Tags") or []) if isinstance(t, str)]
        creatable[name] = "NotCreatable" not in tags and "Service" not in tags
        for m in c["Members"]:
            if m["MemberType"] != "Property":
                continue
            sec = m.get("Security") or {}
            r = sec.get("Read", "None") if isinstance(sec, dict) else sec
            w = sec.get("Write", "None") if isinstance(sec, dict) else sec
            mtags = [t for t in (m.get("Tags") or []) if isinstance(t, str)]
            if "NotScriptable" in mtags:
                reads.setdefault(name, {})[m["Name"]] = "is not scriptable"
                writes.setdefault(name, {})[m["Name"]] = "is not scriptable"
                continue
            if r != "None":
                reads.setdefault(name, {})[m["Name"]] = f"needs {r}"
            if "ReadOnly" in mtags:
                writes.setdefault(name, {})[m["Name"]] = "is read only"
            elif w != "None":
                writes.setdefault(name, {})[m["Name"]] = f"needs {w}"
    out = ["-- Generated by gen_strict.py from the Roblox API dump. Do not edit.", "return {", "\tSuper = {"]
    out += [f"\t\t[{lua_str(k)}] = {lua_str(v)}," for k, v in sorted(supers.items()) if v]
    out.append("\t},")
    for label, table in (("Read", reads), ("Write", writes)):
        out.append(f"\t{label} = {{")
        for cls, props in sorted(table.items()):
            inner = ", ".join(f"[{lua_str(p)}] = {lua_str(why)}" for p, why in sorted(props.items()))
            out.append(f"\t\t[{lua_str(cls)}] = {{ {inner} }},")
        out.append("\t},")
    out.append("\tCreatable = {")
    out += [f"\t\t[{lua_str(k)}] = {'true' if v else 'false'}," for k, v in sorted(creatable.items())]
    out.append("\t},")
    out.append("}")
    (HERE / "strict.luau").write_text("\n".join(out) + "\n")
    print(f"strict.luau: {len(supers)} classes, {sum(map(len, reads.values()))} read / "
          f"{sum(map(len, writes.values()))} write restrictions")


if __name__ == "__main__":
    main(sys.argv[1])
